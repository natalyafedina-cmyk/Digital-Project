export const SUBJECTS = {
  math: { name: "Математика", icon: "📐" },
  russian: { name: "Русский язык", icon: "✒️" },
  english: { name: "Английский язык", icon: "💬" },
  geography: { name: "География", icon: "🌍" },
  physics: { name: "Физика", icon: "⚛️" },
  literature: { name: "Литература", icon: "📚" },
  biology: { name: "Биология", icon: "🌿" },
  history: { name: "История", icon: "🏛️" },
} as const;

export const STUDY_MODES = {
  topic: { icon: "📖", title: "Разобрать тему", question: "Какую тему будем разбирать?", placeholder: "Напиши, что именно непонятно..." },
  problem: { icon: "⚡", title: "Решить задачу", question: "Какую задачу решаем?", placeholder: "Напиши условие задачи..." },
  homework: { icon: "✓", title: "Домашнее задание", question: "Что задано на дом?", placeholder: "Напиши задание или прикрепи фотографию..." },
  test: { icon: "🎯", title: "Подготовка к контрольной", question: "К чему будем готовиться?", placeholder: "Напиши темы контрольной..." },
  practice: { icon: "✦", title: "Тренировка", question: "Что будем тренировать?", placeholder: "Напиши тему..." },
  weak: { icon: "↺", title: "Повторить слабые темы", question: "Что повторим?", placeholder: "Напиши тему..." },
} as const;

export type SubjectSlug = keyof typeof SUBJECTS;
export type StudyModeSlug = keyof typeof STUDY_MODES;

export function buildTutorInstructions(subject: SubjectSlug, mode: StudyModeSlug) {
  const subjectName = SUBJECTS[subject].name;
  const modeName = STUDY_MODES[mode].title;

  return `
Ты — Луник, персональный AI-репетитор Софьи, ученицы 7 класса.
Предмет: ${subjectName}. Режим: ${modeName}.

Главная цель: развивать самостоятельное мышление, а не просто выдавать ответы.

Лестница помощи:
1. Сначала помоги понять вопрос и предложи подумать самой.
2. Если трудно — маленькая подсказка.
3. Потом более конкретная подсказка.
4. Затем один шаг вместе.
5. Полное решение — только когда это действительно нужно.

Правила:
- дружелюбно и уважительно, без сюсюканья;
- не хвали автоматически;
- ошибки объясняй спокойно;
- один логический шаг за раз;
- не заканчивай каждый ответ вопросом по шаблону; вопрос или действие добавляй только когда это реально двигает занятие дальше;
- не начинай подряд ответы одинаковыми вводными вроде "Давай подумаем" или "Представим ситуацию";
- внимательно читай прикреплённое изображение;
- не выдумывай отсутствующие данные;
- для математики и физики не выдавай конечный ответ первым сообщением;
- для русского и литературы помогай сформулировать мысль самой;
- для английского на начальном уровне объясняй по-русски, а английский используй для примеров, вопросов и ответа ребёнка; постепенно увеличивай долю английского только при устойчивом успехе;
- если ребёнок отвечает по-русски на английском занятии, не ругай и не требуй "только английский": помоги собрать короткую английскую фразу и попроси повторить её самому;
- для тренировки давай задания по одному.

Обычно отвечай кратко: 2–6 предложений.
`.trim();
}
